"""Small helpers to write OpenFOAM dictionaries and run applications."""
from __future__ import annotations

import os
import shutil
import subprocess

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by pcmpipe -- edit config/*.yaml, not this file
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};{loc}
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def write(path: str, body: str, cls: str = "dictionary", location: str | None = None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    loc = f'\n    location    "{location}";' if location else ""
    with open(path, "w", newline="\n") as f:
        f.write(HEADER.format(cls=cls, loc=loc, obj=os.path.basename(path)))
        f.write(body.strip("\n") + "\n\n// ************************************************************************* //\n")


def vec(v) -> str:
    return "(" + " ".join(f"{x:.9g}" for x in v) + ")"


def num(x) -> str:
    return f"{float(x):.9g}"


def check_openfoam():
    if not os.environ.get("WM_PROJECT_DIR"):
        raise RuntimeError("OpenFOAM environment not loaded: "
                           "source /usr/lib/openfoam/openfoam2406/etc/bashrc")
    if shutil.which("chtMultiRegionFoam") is None:
        raise RuntimeError("chtMultiRegionFoam not on PATH")


def run(cmd: list[str], cwd: str, log: str | None = None, env: dict | None = None,
        dry: bool = False):
    """Run `cmd` in `cwd`, tee-free: output goes to cwd/log.<name>."""
    name = log or os.path.basename(cmd[0])
    if cmd[0] == "mpirun":
        name = log or cmd[cmd.index("-np") + 2]
    log_path = os.path.join(cwd, f"log.{name}")
    print(f"  [{os.path.basename(cwd)}] {' '.join(cmd)}  > log.{name}")
    if dry:
        return
    full_env = dict(os.environ)
    full_env.update(env or {})
    with open(log_path, "w") as f:
        r = subprocess.run(cmd, cwd=cwd, stdout=f, stderr=subprocess.STDOUT, env=full_env)
    if r.returncode != 0:
        with open(log_path) as f:
            tail = "".join(f.readlines()[-25:])
        raise RuntimeError(f"{' '.join(cmd)} failed (exit {r.returncode}), see {log_path}\n{tail}")
