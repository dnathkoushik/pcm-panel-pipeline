"""Small helpers to write OpenFOAM dictionaries and run applications."""
from __future__ import annotations

import glob
import os
import shlex
import shutil
import subprocess


HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by pcmpipe -- edit config/*.yaml, not this file
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};{loc}
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def write(path: str, body: str, cls: str = "dictionary", location: str | None = None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    loc = f'\n    location    "{location}";' if location else ""
    with open(path, "w", newline="\n") as f:
        f.write(HEADER.format(cls=cls, loc=loc, obj=os.path.basename(path)))
        f.write(body.strip("\n") + "\n\n// ************************************************************************* //\n")


def vec(v) -> str:
    return "(" + " ".join(f"{x:.9g}" for x in v) + ")"


def num(x) -> str:
    return f"{float(x):.9g}"


# Where FreeCAD / ParaView usually live when they are not on PATH
_CANDIDATES = {
    "freecadcmd": ["freecadcmd", "FreeCADCmd", "freecad.cmd",
                   "/Applications/FreeCAD.app/Contents/Resources/bin/freecadcmd",
                   "/Applications/FreeCAD.app/Contents/MacOS/FreeCADCmd",
                   "/Applications/FreeCAD.app/Contents/Resources/bin/FreeCADCmd"],
    "pvpython": ["pvpython", "/Applications/ParaView*.app/Contents/bin/pvpython"],
    "mpirun": ["mpirun"],
}


def tool(case: dict, name: str) -> list[str]:
    """Command for an external tool, as an argv prefix.

    Priority: environment variable PCMPIPE_<NAME> (e.g. PCMPIPE_PVPYTHON="xvfb-run -a
    pvpython"), then `tools.<name>` in base_case.yaml, then common install locations
    (macOS app bundles, snap). Values may contain arguments.
    """
    value = os.environ.get(f"PCMPIPE_{name.upper()}") or case.get("tools", {}).get(name, name)
    argv = shlex.split(value)
    if shutil.which(argv[0]):
        return argv
    for cand in _CANDIDATES.get(name, []):
        for path in sorted(glob.glob(cand)) if "*" in cand else [cand]:
            if shutil.which(path) or (os.path.isfile(path) and os.access(path, os.X_OK)):
                return [path] + argv[1:]
    return argv     # let the caller report "not found"


def check_openfoam():
    if not os.environ.get("WM_PROJECT_DIR"):
        raise RuntimeError(
            "OpenFOAM environment not loaded. Source its etc/bashrc first, e.g.\n"
            "  Ubuntu/WSL : source /usr/lib/openfoam/openfoam2406/etc/bashrc\n"
            "  macOS app  : run `openfoam2406` (OpenFOAM.app) and work in that shell\n"
            "  Docker     : scripts/docker_run.sh does this for you")
    if shutil.which("chtMultiRegionFoam") is None:
        raise RuntimeError("chtMultiRegionFoam not on PATH (need OpenFOAM v2306+ from openfoam.com)")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if " " in root:
        raise RuntimeError(f"project path contains spaces ({root}); OpenFOAM and wmake "
                           "cannot handle that -- clone/copy the repository to a path without spaces")


def run(cmd: list[str], cwd: str, log: str | None = None, env: dict | None = None,
        dry: bool = False):
    """Run `cmd` in `cwd`, tee-free: output goes to cwd/log.<name>."""
    name = log or os.path.basename(cmd[0])
    if not log and "-np" in cmd and os.path.basename(cmd[0]) == "mpirun":
        name = cmd[cmd.index("-np") + 2]
    log_path = os.path.join(cwd, f"log.{name}")
    print(f"  [{os.path.basename(cwd)}] {' '.join(cmd)}  > log.{name}")
    if dry:
        return
    full_env = dict(os.environ)
    full_env.update(env or {})
    with open(log_path, "w") as f:
        r = subprocess.run(cmd, cwd=cwd, stdout=f, stderr=subprocess.STDOUT, env=full_env)
    if r.returncode != 0:
        with open(log_path) as f:
            tail = "".join(f.readlines()[-25:])
        raise RuntimeError(f"{' '.join(cmd)} failed (exit {r.returncode}), see {log_path}\n{tail}")
